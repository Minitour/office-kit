def write_text(path: Path, content: str) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(normalize_text(content))


def normalize_text(content: str) -> str:
    if not content.endswith("\n"):
        content += "\n"
    return content


def load_model(brand_dir: Path) -> dict[str, Any]:
    return validate(load_brand(brand_dir / "brand.json"), brand_dir)


def render_all(model: Mapping[str, Any]) -> dict[str, str]:
    writers = {
        "BRAND.md": render_brand_md,
        "tokens.css": render_tokens_css,
        "frame.md": render_frame_md,
    }
    return {name: normalize_text(writers[name](model)) for name in DERIVATIVES}


def generate(brand_dir: Path) -> list[Path]:
    expected = render_all(load_model(brand_dir))
    written: list[Path] = []
    for name in DERIVATIVES:
        path = brand_dir / name
        write_text(path, expected[name])
        written.append(path)
    return written


def check(brand_dir: Path) -> list[tuple[str, Path]]:
    """Compare on-disk derivatives to an in-memory render. Does not write."""
    expected = render_all(load_model(brand_dir))
    problems: list[tuple[str, Path]] = []
    for name in DERIVATIVES:
        path = brand_dir / name
        if not path.is_file():
            problems.append(("missing", path))
            continue
        actual = path.read_bytes()
        if actual != expected[name].encode("utf-8"):
            problems.append(("stale", path))
    return problems


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Validate brand.json and regenerate BRAND.md, tokens.css, and frame.md."
    )
    parser.add_argument(
        "--brand-dir",
        type=Path,
        default=None,
        help="Brand directory (default: <repo>/brand)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Validate and compare derivatives in memory; do not write files.",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    brand_dir = (args.brand_dir or (repo_root() / "brand")).resolve()
    try:
        if args.check:
            problems = check(brand_dir)
        else:
            written = generate(brand_dir)
    except BrandError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if args.check:
        if problems:
            print("error: generated files are not current:", file=sys.stderr)
            for status, path in problems:
                print(f"  {status}: {path}", file=sys.stderr)
            return 1
        print("ok")
        return 0
    for path in written:
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
